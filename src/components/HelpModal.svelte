<h5>Key bindings</h5>
<ul>
	<li><p><strong>H</strong> to display Help</p></li>
	<!-- NOT YET IMPLEMENTED -->
	<li><p><strong>M</strong> to enter a Miss</p></li>
	<!-- NOT YET IMPLEMENTED -->
	<li>
		<p>
			<strong>P</strong> to enter a Pot, followed by score value
		</p>
	</li>
	<!-- NOT YET IMPLEMENTED -->
	<li><p><strong>F</strong> to enter a Foul, followed by penalty value</p></li>
	<!-- NOT YET IMPLEMENTED -->
	<li><p><strong>1</strong>, <strong>2</strong>, etc... to enter a value</p></li>
	<!-- NOT YET IMPLEMENTED -->
	<li>
		<p>
			<strong>S</strong> to indicate that the cue-ball is snookered
		</p>
	</li>
	<!-- NOT YET IMPLEMENTED -->
	<li>
		<p>
			<strong>C</strong> ("Collateral") while pressing a value to indicate that a subsequent red
			ball has been pocketted
		</p>
	</li>
	<!-- NOT YET IMPLEMENTED -->
	<li>
		<p>
			<strong>R</strong> to indicate that the player has requested an opponent to play again
		</p>
	</li>
	<!-- NOT YET IMPLEMENTED -->
	<li>
		<p>
			<strong>O</strong> to indicate that the next stroke will be on a free ball
		</p>
	</li>
</ul>

<h5>Pot points:</h5>
<ul>
	<li><p>Black: <strong>7</strong> points</p></li>
	<li><p>Pink: <strong>6</strong> points</p></li>
	<li><p>Blue: <strong>5</strong> points</p></li>
	<li><p>Brown: <strong>4</strong> points</p></li>
	<li><p>Green: <strong>3</strong> points</p></li>
	<li><p>Yellow: <strong>2</strong> points</p></li>
	<li><p>Red: <strong>1</strong> points</p></li>
</ul>

<h5>Foul penalty:</h5>
<p>
	is relative of the value of the ball on or ball concerned, whichever is higher, with the minimum
	penalty of 4 points.
</p>
